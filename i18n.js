const CC_LANGUAGES = [{"code":"en","name":"English"},{"code":"de","name":"Deutsch"},{"code":"es","name":"Español"},{"code":"fr","name":"Français"},{"code":"it","name":"Italiano"},{"code":"pt","name":"Português"},{"code":"nl","name":"Nederlands"},{"code":"pl","name":"Polski"},{"code":"tr","name":"Türkçe"},{"code":"ru","name":"Русский"},{"code":"ja","name":"日本語"},{"code":"zh","name":"中文"},{"code":"ko","name":"한국어"}];

/* Shared runtime: storage-safe selection, per-key fallbacks and text-only rendering. */
(function () {
  const supported=new Set(CC_LANGUAGES.map(language=>language.code));
  const normalize=value=>typeof value==='string'?value.trim().toLowerCase().replace(/_/g,'-').split('-')[0]:'';
  function read(){try{return localStorage.getItem('cc_lang');}catch{return null;}}
  function preferred(){
    const saved=normalize(read());if(supported.has(saved))return saved;
    for(const value of navigator.languages||[navigator.language||'en']){const code=normalize(value);if(supported.has(code))return code;}
    return 'en';
  }
  let current=preferred();
  function translate(key,...args){
    const value=CC_TRANSLATIONS[current]?.[key]??CC_TRANSLATIONS.en[key]??key;
    return String(value).replace(/\{(\d+)\}/g,(match,index)=>args[index]===undefined?match:String(args[index]));
  }
  function argumentsFor(element){try{const args=JSON.parse(element.dataset.tArgs||'[]');return Array.isArray(args)?args:[];}catch{return [];}}
  const navKeys={'download.html':'nav_downloads','changelog.html':'nav_changelog','settings.html':'nav_settings','messages.html':'nav_messages','bugreport.html':'nav_bugreport','plugins.html':'nav_plugins','profile.html':'nav_profile','questions.html':'nav_questions','announcements.html':'nav_ann'};
  function bindNavigation(root){
    root.querySelectorAll('.drawer-nav a[href],#q-menu a[href],nav a[href]').forEach(link=>{
      if(link.matches('.nav-logo,.q-logo,.drawer-logo,.nav-avatar')||link.closest('.user-badge'))return;
      if(link.matches('[data-t]')||link.querySelector('[data-t]'))return;
      let key;try{key=navKeys[new URL(link.getAttribute('href'),location.href).pathname.split('/').pop()];}catch{return;}
      if(!key||/Conch|Cmdr|Sentinel/.test(link.textContent))return;
      if(link.classList.contains('nav-back'))key='back';
      if(!/\p{L}/u.test(link.textContent)){link.dataset.tTitle=key;link.dataset.tAriaLabel=key;return;}
      const textNode=[...link.childNodes].reverse().find(node=>node.nodeType===3&&/\p{L}/u.test(node.textContent));
      let label=link.querySelector('span:not(.drawer-icon):not(.drawer-item-icon):last-child');
      if(textNode){label=document.createElement('span');const prefix=textNode.textContent.match(/^\s*([←→↓↑]\s*)/)?.[1];textNode.replaceWith(...(prefix?[document.createTextNode(prefix),label]:[label]));}
      else if(!label){if(link.children.length)return;label=link;}
      label.dataset.t=key;
    });
  }
  function languageOptions(root){
    root.querySelectorAll('[data-language-select]').forEach(select=>{
      if(select.dataset.languagesReady!=='1'){
        select.replaceChildren(...CC_LANGUAGES.map(language=>{
          const option=document.createElement('option');option.value=language.code;
          option.textContent=select.dataset.languageSelect==='compact'?language.code.toUpperCase():language.name;
          option.title=language.name;option.lang=language.code;return option;
        }));select.dataset.languagesReady='1';
      }
      select.value=current;select.title=translate('display_language');select.setAttribute('aria-label',translate('display_language'));
    });
  }
  function apply(root=document){
    bindNavigation(root);languageOptions(root);
    const elements=[...(root.matches?.('[data-t],[data-t-title],[data-t-placeholder],[data-t-aria-label]')?[root]:[]),...root.querySelectorAll('[data-t],[data-t-title],[data-t-placeholder],[data-t-aria-label]')];
    elements.forEach(element=>{
      const args=argumentsFor(element);
      if(element.dataset.t){const value=translate(element.dataset.t,...args);if(element.matches('input,textarea'))element.placeholder=value;else element.textContent=value;}
      for(const [attribute,key] of [['title','tTitle'],['placeholder','tPlaceholder'],['aria-label','tAriaLabel']])if(element.dataset[key])element.setAttribute(attribute,translate(element.dataset[key],...args));
    });
    document.documentElement.lang=current;
  }
  function changed(){apply();window.dispatchEvent(new CustomEvent('cc:language-change',{detail:{language:current}}));}
  function setLanguage(value){
    const code=normalize(value);current=supported.has(code)?code:'en';
    try{localStorage.setItem('cc_lang',current);}catch{}
    changed();return current;
  }
  window.CC_I18N={t:translate,apply,setLanguage,get language(){return current;},languages:CC_LANGUAGES.map(language=>Object.freeze({...language}))};
  window.t=translate;window.applyTranslations=apply;
  window.addEventListener('storage',event=>{if(event.key==='cc_lang'||event.key===null){current=preferred();changed();}});
  if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',changed,{once:true});else changed();
})();
